def _language_candidates(value: str) -> list[str]:
    return [part.strip() for part in value.replace(";", ":").split(":") if part.strip()]


def _normalize_language(value: str) -> str:
    normalized = value.strip().lower().replace("_", "-")
    if "." in normalized:
        normalized = normalized.split(".", 1)[0]
    return normalized


def _match_language(value: str) -> str | None:
    language = _normalize_language(value)
    if not language:
        return None
    if (
        "tchinese" in language
        or "traditional" in language
        or "zh-hant" in language
        or language == "zh-tw"
        or language.startswith("zh-hk")
        or language.startswith("zh-mo")
    ):
        return "zh-tw"
    if (
        "schinese" in language
        or "simplified" in language
        or "zh-hans" in language
        or language == "zh"
        or language.startswith("zh-cn")
        or language.startswith("zh-sg")
    ):
        return "zh"
    aliases = (
        ("es-419", ("latam", "es-419")),
        ("pt-br", ("brazilian", "pt-br")),
        ("ar", ("arabic", "ar")),
        ("bg", ("bulgarian", "bg")),
        ("cs", ("czech", "cs")),
        ("da", ("danish", "da")),
        ("nl", ("dutch", "nl")),
        ("fi", ("finnish", "fi")),
        ("el", ("greek", "el")),
        ("hu", ("hungarian", "hu")),
        ("id", ("indonesian", "id")),
        ("it", ("italian", "it")),
        ("ms", ("malay", "ms")),
        ("no", ("norwegian", "no", "nb", "nn")),
        ("pl", ("polish", "pl")),
        ("pt", ("portuguese", "pt")),
        ("ro", ("romanian", "ro")),
        ("sv", ("swedish", "sv")),
        ("th", ("thai", "th")),
        ("tr", ("turkish", "tr")),
        ("uk", ("ukrainian", "uk")),
        ("vi", ("vietnamese", "vi")),
        ("ja", ("japanese", "ja")),
        ("ko", ("koreana", "korean", "ko")),
        ("de", ("german", "de")),
        ("fr", ("french", "fr")),
        ("es", ("spanish", "es")),
        ("ru", ("russian", "ru")),
        ("en", ("english", "en")),
    )
    for resolved, prefixes in aliases:
        if any(language == prefix or language.startswith(prefix + "-") for prefix in prefixes):
            return resolved
    return None


def resolve_language(values: Iterable[str]) -> str:
    for value in values:
        if not isinstance(value, str):
            continue
        for candidate in _language_candidates(value):
            resolved = _match_language(candidate)
            if resolved is not None:
                return resolved
    return "en"


def _config_value(path: Path, section: str, option: str) -> str:
    parser = configparser.ConfigParser(interpolation=None)
    try:
        with path.open(encoding="utf-8") as handle:
            parser.read_file(handle)
    except (OSError, configparser.Error, UnicodeError):
        return ""
    if not parser.has_section(section):
        return ""
    return parser.get(section, option, fallback="")


def _running_steam_ui_languages(proc_root: Path) -> list[str]:
    try:
        processes = sorted(
            (path for path in proc_root.iterdir() if path.name.isdigit()),
            key=lambda path: int(path.name),
            reverse=True,
        )
    except OSError:
        return []
    languages: list[str] = []
    for process in processes:
        try:
            arguments = [
                argument.decode(errors="replace")
                for argument in (process / "cmdline").read_bytes().split(b"\0")
                if argument
            ]
        except OSError:
            continue
        if not any("steamwebhelper" in argument.lower() for argument in arguments):
            continue
        for argument in arguments:
            if argument.lower().startswith("-lang="):
                languages.append(argument.split("=", 1)[1])
                break
    return languages


def _persisted_steam_languages(home: Path) -> list[str]:
    registry_paths = (
        home / ".steam" / "registry.vdf",
        home / ".local" / "share" / "Steam" / "registry.vdf",
    )
    seen: set[Path] = set()
    languages: list[str] = []
    for path in registry_paths:
        try:
            resolved = path.resolve()
        except OSError:
            resolved = path
        if resolved in seen:
            continue
        seen.add(resolved)
        try:
            lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            continue
        found: list[str] = []
        for line in lines:
            fields = line.strip().split('"')
            if len(fields) >= 4 and fields[1].lower() == "language":
                found.append(fields[3])
        languages.extend(reversed(found))
    return languages


def detect_system_language(
    *,
    environ: Mapping[str, str] | None = None,
    home: Path | None = None,
    proc_root: Path | None = None,
) -> str:
    environment = os.environ if environ is None else environ
    user_home = Path.home() if home is None else Path(home)
    processes = Path("/proc") if proc_root is None else Path(proc_root)
    plasma_locale = user_home / ".config" / "plasma-localerc"
    kde_globals = user_home / ".config" / "kdeglobals"
    values = [
        *_running_steam_ui_languages(processes),
        *_persisted_steam_languages(user_home),
        _config_value(plasma_locale, "Translations", "LANGUAGE"),
        _config_value(kde_globals, "Locale", "Language"),
        environment.get("LANGUAGE", ""),
        environment.get("LC_ALL", ""),
        environment.get("LC_MESSAGES", ""),
        _config_value(plasma_locale, "Formats", "LANG"),
        environment.get("LANG", ""),
    ]
    return resolve_language(values)


def translate(key: str, language: str, **values: object) -> str:
    table = DESKTOP_TEXT.get(language, DESKTOP_TEXT["en"])
    template = table.get(key, DESKTOP_TEXT["en"].get(key, key))
    return template.format(**values)
